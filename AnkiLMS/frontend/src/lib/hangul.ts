const INITIALS = ["ㄱ", "ㄲ", "ㄴ", "ㄷ", "ㄸ", "ㄹ", "ㅁ", "ㅂ", "ㅃ", "ㅅ", "ㅆ", "ㅇ", "ㅈ", "ㅉ", "ㅊ", "ㅋ", "ㅌ", "ㅍ", "ㅎ"];
const VOWELS = ["ㅏ", "ㅐ", "ㅑ", "ㅒ", "ㅓ", "ㅔ", "ㅕ", "ㅖ", "ㅗ", "ㅘ", "ㅙ", "ㅚ", "ㅛ", "ㅜ", "ㅝ", "ㅞ", "ㅟ", "ㅠ", "ㅡ", "ㅢ", "ㅣ"];
export const HANGUL_FINALS = ["ㄱ", "ㄲ", "ㄳ", "ㄴ", "ㄵ", "ㄶ", "ㄷ", "ㄹ", "ㄺ", "ㄻ", "ㄼ", "ㄽ", "ㄾ", "ㄿ", "ㅀ", "ㅁ", "ㅂ", "ㅄ", "ㅅ", "ㅆ", "ㅇ", "ㅈ", "ㅊ", "ㅋ", "ㅌ", "ㅍ", "ㅎ"];

export function composeHangulSyllable(initial: string, vowel: string, final = ""): string {
  const initialIndex = INITIALS.indexOf(initial);
  const vowelIndex = VOWELS.indexOf(vowel);
  const finalIndex = final ? HANGUL_FINALS.indexOf(final) + 1 : 0;
  if (initialIndex < 0 || vowelIndex < 0 || (final && finalIndex === 0)) return `${initial}${vowel}${final}`;
  return String.fromCharCode(0xac00 + (initialIndex * VOWELS.length + vowelIndex) * 28 + finalIndex);
}
